"""Bundled workflow template library and copy-based install.

Repository layout::

    library/
      INDEX.md                 # generated by `aiwf wf index`
      workflows/<id>.json      # workflow definitions, and nothing else
      meta/<id>.json           # when-to-use metadata, never installed

Resolution mirrors the bundled-skills mechanism: ``AIWF_LIBRARY_DIR`` wins,
otherwise ``<repo>/library/workflows`` is derived from this file's location.

Metadata lives in a *sibling* directory rather than as ``<id>.meta.json``
beside the definition, on purpose: ``Storage.list_workflows`` treats every
``*.json`` under ``.aiwf/workflows`` as a definition, so a metadata file that
ever reached a project would be picked up by ``aiwf validate --project`` and
fail schema validation. Keeping it out of the definitions directory removes
that footgun.

Install is copy-based. That is a deliberate choice: templates are immature, so
a project wants its own editable copy rather than a reference it must not
touch. Two consequences follow, and this module handles them rather than
leaving them to the caller:

* **dependency closure** - a definition that calls another through ``subflow``
  or ``foreach.workflow`` is unusable without it, so install pulls the closure
  and raises when a called workflow is in neither the library nor the project;
* **provenance** - ``<root>/installed.json`` records the installed bytes and
  the library state at install time, so a locally edited copy is never
  overwritten without ``--force`` and upstream updates stay visible.
"""
import copy
import difflib
import hashlib
import json
import os
from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple

from .paths import data_candidates

LEDGER_NAME = "installed.json"
PREFIX = "std."  # naming convention for library templates; not enforced


# ---- paths ---------------------------------------------------------------
def library_dir(explicit: Optional[str] = None) -> str:
    if explicit:
        return os.path.abspath(explicit)
    env_dir = os.getenv("AIWF_LIBRARY_DIR")
    if env_dir:
        return os.path.abspath(env_dir)
    # engine/aiwf/library.py -> <repo>/library/workflows
    repo_root = os.path.dirname(
        os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    )
    checkout = os.path.join(repo_root, "library", "workflows")
    if os.path.isdir(checkout):
        return checkout
    for candidate in data_candidates("library", "workflows"):
        if os.path.isdir(candidate):
            return candidate
    return checkout


def meta_dir(library: Optional[str] = None) -> str:
    return os.path.join(os.path.dirname(library_dir(library)), "meta")


def index_path(library: Optional[str] = None) -> str:
    return os.path.join(os.path.dirname(library_dir(library)), "INDEX.md")


def ledger_path(storage) -> str:
    return os.path.join(storage.root, LEDGER_NAME)


# ---- small helpers -------------------------------------------------------
def _read_text(path: str) -> Optional[str]:
    if not os.path.isfile(path):
        return None
    with open(path, "r", encoding="utf-8-sig") as handle:
        return handle.read()


def _digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def _now_iso() -> str:
    return datetime.now().astimezone().isoformat(timespec="seconds")


def read_ledger(storage) -> Dict[str, Any]:
    text = _read_text(ledger_path(storage))
    if not text:
        return {}
    try:
        value = json.loads(text)
    except ValueError:
        return {}
    return value if isinstance(value, dict) else {}


def write_ledger(storage, ledger: Dict[str, Any]) -> str:
    storage._atomic_write_text(
        ledger_path(storage),
        json.dumps(ledger, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
    )
    return ledger_path(storage)


# ---- library contents ----------------------------------------------------
def load_meta(entry_id: str, library: Optional[str] = None) -> Dict[str, Any]:
    text = _read_text(os.path.join(meta_dir(library), f"{entry_id}.json"))
    if not text:
        return {}
    try:
        value = json.loads(text)
    except ValueError:
        return {}
    return value if isinstance(value, dict) else {}


def load_library(library: Optional[str] = None) -> Dict[str, Dict[str, Any]]:
    """id -> {id, path, text, definition, meta} for every library template."""
    base = library_dir(library)
    if not os.path.isdir(base):
        raise FileNotFoundError(f"template library not found at {base}")
    entries: Dict[str, Dict[str, Any]] = {}
    for name in sorted(os.listdir(base)):
        if not name.endswith(".json") or name.startswith("."):
            continue
        path = os.path.join(base, name)
        with open(path, "r", encoding="utf-8-sig") as handle:
            text = handle.read()
        definition = json.loads(text)
        entry_id = definition.get("id") or name[:-5]
        entries[entry_id] = {
            "id": entry_id,
            "path": path,
            "text": text,
            "definition": definition,
            "meta": load_meta(entry_id, library),
        }
    return entries


def workflow_refs(definition: Dict[str, Any]) -> List[str]:
    """Workflow ids the definition calls, including nested inline bodies."""
    found: List[str] = []

    def walk(node: Dict[str, Any]) -> None:
        if node.get("type") in ("subflow", "foreach") and node.get("workflow"):
            found.append(node["workflow"])
        for child in node.get("nodes") or []:
            if isinstance(child, dict):
                walk(child)

    for node in definition.get("nodes") or []:
        if isinstance(node, dict):
            walk(node)
    return found


def dependency_closure(
    root_id: str,
    entries: Dict[str, Dict[str, Any]],
    local_ids: Optional[set] = None,
) -> List[str]:
    """Template ids to install for ``root_id``: dependencies first, root last.

    Dependencies the project already provides (``local_ids``) are not installed
    and not reported. A called workflow present in neither the library nor the
    project is an error: silently skipping it is what produces a definition
    that cannot even pass ``validate --project``.
    """
    local_ids = local_ids or set()
    ordered: List[str] = []
    visiting: List[str] = []

    def visit(entry_id: str, required_by: Optional[str], is_root: bool) -> None:
        if entry_id in ordered:
            return
        entry = entries.get(entry_id)
        if entry is None:
            if not is_root and entry_id in local_ids:
                return
            where = f"template {required_by!r} calls" if required_by else "template"
            raise ValueError(
                f"{where} {entry_id!r}, which is in neither the library "
                f"({library_dir()}) nor this project"
            )
        if entry_id in visiting:
            chain = visiting[visiting.index(entry_id):] + [entry_id]
            raise ValueError(f"template dependency cycle: {' -> '.join(chain)}")
        visiting.append(entry_id)
        for ref in workflow_refs(entry["definition"]):
            visit(ref, entry_id, False)
        visiting.pop()
        ordered.append(entry_id)

    visit(root_id, None, True)
    return ordered


# ---- install -------------------------------------------------------------
def install(
    storage,
    entry_id: str,
    as_id: Optional[str] = None,
    force: bool = False,
    with_deps: bool = True,
    library: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """Copy a library template (and its closure) into the project.

    Refuses, before writing anything, when a target file exists and its content
    no longer matches what install recorded - that is a locally edited copy,
    and overwriting it silently is exactly what copy-based installs must not
    do. ``--force`` is the explicit override.
    """
    entries = load_library(library)
    if entry_id not in entries:
        raise ValueError(
            f"template {entry_id!r} not found in the library at "
            f"{library_dir(library)}"
        )
    local_ids = set(storage.list_workflows())
    ids = (
        dependency_closure(entry_id, entries, local_ids)
        if with_deps else [entry_id]
    )

    ledger = read_ledger(storage)
    plan: List[Dict[str, Any]] = []
    refused: List[str] = []
    for template_id in ids:
        target_id = as_id if (template_id == entry_id and as_id) else template_id
        dest = storage.workflow_path(target_id)
        existing = _read_text(dest)
        if existing is not None:
            record = ledger.get(target_id)
            edited = record is None or _digest(existing) != record.get(
                "installed_hash"
            )
            if edited and not force:
                reason = (
                    "not installed by aiwf" if record is None
                    else "edited locally since install"
                )
                refused.append(f"  {target_id}  ({dest}) - {reason}")
        plan.append({"template_id": template_id, "target_id": target_id,
                     "dest": dest, "existed": existing is not None})
    if refused:
        raise ValueError(
            "refusing to overwrite existing local workflows:\n"
            + "\n".join(refused)
            + "\nre-run with --force to overwrite, or --as <new-id> to install "
              "under a different id"
        )

    installed: List[Dict[str, Any]] = []
    for item in plan:
        entry = entries[item["template_id"]]
        content = entry["text"]
        if item["target_id"] != item["template_id"]:
            definition = copy.deepcopy(entry["definition"])
            definition["id"] = item["target_id"]
            content = json.dumps(definition, ensure_ascii=False, indent=2) + "\n"
        storage._atomic_write_text(item["dest"], content)
        ledger[item["target_id"]] = {
            "source": entry["path"],
            "source_id": item["template_id"],
            "installed_hash": _digest(content),
            "upstream_hash": _digest(entry["text"]),
            "installed_at": _now_iso(),
            "maturity": (entry["meta"] or {}).get("maturity"),
        }
        installed.append({
            "id": item["target_id"],
            "template_id": item["template_id"],
            "path": item["dest"],
            "dependency": item["target_id"] != entry_id,
            "updated": item["existed"],
        })
    write_ledger(storage, ledger)
    return installed


# ---- inspection ----------------------------------------------------------
def status(storage, library: Optional[str] = None) -> List[Dict[str, Any]]:
    """Installed templates vs the library: locally edited? upstream moved?"""
    try:
        entries = load_library(library)
    except FileNotFoundError:
        entries = {}
    rows: List[Dict[str, Any]] = []
    for target_id, record in sorted(read_ledger(storage).items()):
        current = _read_text(storage.workflow_path(target_id))
        upstream = entries.get(record.get("source_id") or target_id)
        if current is None:
            state = "missing"
        elif _digest(current) != record.get("installed_hash"):
            state = "edited"
        else:
            state = "clean"
        if upstream is None:
            upstream_state = "unknown"
        elif _digest(upstream["text"]) != record.get("upstream_hash"):
            upstream_state = "updated"
        else:
            upstream_state = "current"
        rows.append({
            "id": target_id,
            "state": state,
            "upstream": upstream_state,
            "maturity": record.get("maturity"),
            "installed_at": record.get("installed_at"),
            "path": storage.workflow_path(target_id),
        })
    return rows


def diff(
    storage, entry_id: str, library: Optional[str] = None
) -> Tuple[str, str, str]:
    """Unified diff of the local copy against the library version."""
    entries = load_library(library)
    record = read_ledger(storage).get(entry_id) or {}
    source_id = record.get("source_id") or entry_id
    if source_id not in entries:
        raise ValueError(
            f"template {source_id!r} not found in the library at "
            f"{library_dir(library)}"
        )
    local = _read_text(storage.workflow_path(entry_id))
    if local is None:
        raise ValueError(f"{entry_id!r} is not installed in this project")
    upstream = entries[source_id]["text"]
    rendered = "".join(difflib.unified_diff(
        upstream.splitlines(keepends=True),
        local.splitlines(keepends=True),
        fromfile=f"library/{source_id}.json",
        tofile=f"local/{entry_id}.json",
    ))
    return rendered, local, upstream


def render_index(library: Optional[str] = None) -> str:
    """Markdown catalogue generated from the library's metadata."""
    entries = load_library(library)
    lines = [
        "# aiwf 模板库目录",
        "",
        "由 `aiwf wf index` 生成，请勿手改——改各模板的 `meta/<id>.json` 后重新生成。",
        "",
        "安装：`aiwf wf install <id>`（默认连同依赖一起装；装完跑 `aiwf validate --project`）。",
        "",
    ]
    for entry_id in sorted(entries):
        entry = entries[entry_id]
        meta = entry["meta"] or {}
        definition = entry["definition"]
        lines.append(f"## `{entry_id}`")
        lines.append("")
        summary = meta.get("summary") or definition.get("description") or ""
        lines.append(f"- 成熟度：`{meta.get('maturity', 'unspecified')}`")
        if summary:
            lines.append(f"- 一句话：{summary}")
        deps = dependency_closure(entry_id, entries)
        lines.append(
            "- 依赖："
            + (", ".join(f"`{d}`" for d in deps if d != entry_id) or "无")
        )
        lines.append(f"- 版本：`{definition.get('schema_version')}`")
        for label, key in (("适用", "scenarios"), ("不适用", "not_for")):
            values = meta.get(key) or []
            if values:
                lines.append(f"- {label}：")
                lines.extend(f"  - {value}" for value in values)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"
